'''
@file StateSaveRestore.py
@brief Scaffolding for saving and restoring system state.
@author Ron Fox

This file contains base class software and a manager class
to handle saving and restoring the state of pyReadout .. though,
in theory it could make this possible for any program.

The main concept:  every segment of the program which
needs to save state will register a Serializer
object (instance of a subclass of the Serializer
class defined in this file.)  See more
about this class at the definition of that
abstract base class below.

When a program is exiting or saving state, 
it will ask the SerializationManager to iterate over
the serializer instances invoking their serialize
method.   Serialize is expected to produce valid
Python3 code that can later be imported back into
the program when it starts up later.

At that time, the generted module is imported and, in case
it's necessary to do something to complete the load each
Serializer's deserialize method is invoked.  For example,
the run number could be saved like:

run_number = 1234

The deserialize methd might then need to:

gui.setRunNumber(readouguiinit.run_number) to incorporate that
into the full system.

Nothing is done to ensure the generated code is valid Python.
That's up to each Seralizer.serialize method. If it isn't the
pyReadoutGui startup will fail with the appropriate error.
'''
import io
import traceback
import types
from abc import ABC, abstractmethod
from typing import ClassVar, Self


class Serializer(ABC):
    '''
        This base class provides a definition that concrete
        configuration serialization classes must implement.
        In order to function properly, concrete  instances
        must be instantiated and then registered with the
        SerializationManager singleton below.
    '''
    @abstractmethod
    def serialize(self, destination : io.TextIOBase) -> None:
        '''
            Save the python code that captures the state this
            Serializer wants to maintain
            
            @param destination : io.TextIOBase - the file handle to which
               to write python code.
            @note On entry, assume you are at indentation level 0.
        '''
        
        ...
    @abstractmethod        
    def deserialize(self, restored : types.ModuleType) -> None:
        '''
           Given that the module generated by serializing
           the configuratino has been loaded,  Restore
           the configuration from that module.
           @param restored : types.Module - the module that was
                loaded by the restoration operation.  E.g.
                if you saved 
run_number = 5
                You can refer to that as 
                    restored.run_number.
        '''
        
        ...
        
class SerializationManager:
    _instance : ClassVar[None | Self] = None
    
    def __init__(self) -> None:
        '''
        Create a new instance of the class.  This should not be called
        directly, as SerializationManager is a singleton.  Invoke the
        instance() method to get a reference to the singleton instance.
        
        If an external file attempts to invoke us we raise a TypeError.
        '''
        
        # Validate the caller:
        
        caller = traceback.extract_stack()[-2]
        if caller.filename != __file__:
            raise TypeError(
                f'Attempted to call SerializationManager __init__ from {caller.filename} use instance class method'
            )
        
        self._serializers : list[Serializer] = []
    
    @classmethod
    def instance(cls) -> Self:
        '''
        @return SerializationManager - the singleton instance.
        '''
        
        
        if not cls._instance:
            cls._instance = cls()
        return cls._instance
    

    def serialize(self, destination : io.TextIOBase) -> None:
        for serializer in self._serializers:
            destination.write(f'#  configuration from  {type(serializer).__name__} \n')
            serializer.serialize(destination)
    def deserialize(self, module : types.ModuleType) -> None:
        for serializer in self._serializers:
            serializer.deserialize(module)

    def addSerializer(self, serializer : Serializer) -> None:
        self._serializers.append(serializer)

# Tests:
if __name__ == '__main__':
    import sys
    import unittest
    class SerializationManagerTests(unittest.TestCase):
        class TestSerializer(Serializer):
            def __init__(self):
                self._data = None
            def serialize(self, dest : io.TextIOBase) -> None:
                dest.write('a=1  # This is my saved stuff\n')
            def deserialize(self, module : types.ModuleType) -> None:
                self._data = module.a
        
        #  We'll output to a stream which
        #  will be imported as 'saved'.
        #  setup will create the stream and
        #  teardown will remove the module from
        #  the cache...
        #  _load  is a utility each test can use to
        #  load the module.
        
        def setUp(self) -> None:
            self._output = io.StringIO()
            self._manager = SerializationManager()
        def tearDown(self) -> None:
            try:
                del sys.modules['saved']
            except KeyError:
                pass                      # Module might not be made in all tests
            self._manager = None
        def _load(self) -> None:
            module_name = 'saved'
            self._module       = types.ModuleType(module_name)
            self._output.seek(0)
            exec(self._output.read(), self._module.__dict__)
            sys.modules[module_name] = self._module
        
        def test_empty(self):
            # With no Serializers I get an empty file:
            
            self._manager.serialize(self._output)
            contents = self._output.getvalue()
            self.assertEqual('', contents)
            
            # Make sure the load crap works too:
            
            try:
                self._load()
            except Exception:  # noqa: BLE001
                self.fail('Could not load the module')
        
        def test_serdes(self):
            test_obj = SerializationManagerTests.TestSerializer()
            self._manager.addSerializer(test_obj)
            self._manager.serialize(self._output)
            self._load()
            self._manager.deserialize(self._module)
            
            self.assertEqual(1, test_obj._data)
            
            
    unittest.main()